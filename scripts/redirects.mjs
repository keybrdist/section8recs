// Write static/_redirects for Cloudflare Pages: every address section8recs.com has used for a release goes to its
// /cat/<CAT> page with a 301. Static rules come first (Pages allows 2,000 static and 100 dynamic). Releases that left
// the catalogue get no rules, so their old addresses answer 404 instead of redirecting somewhere unrelated.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const { releases } = JSON.parse(readFileSync(ROOT + 'site/data/catalog.json', 'utf8'));
const legacy = JSON.parse(readFileSync(ROOT + 'site/data/legacy-urls.json', 'utf8'));
const byCat = new Map(releases.map(r => [r.cat, r])), byId = new Map(releases.map(r => [String(r.id), r]));
// lgsites built /r/<slug>/<id> slugs from artist and title
const lgSlug = r => `${r.artist} ${r.title}`.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');

const rules = new Map();
// Pages reads ':' and '*' in a source as placeholders, so the few archived slugs containing them are left out
const add = (from, r) => { if (r && !/[:*]/.test(from) && from !== `/cat/${r.cat}` && !rules.has(from)) rules.set(from, `/cat/${r.cat}`); };
for (const r of releases) {
  if (r.label === 'section8recs') add(`/r/section8recs/${r.id}`, r);   // lgsites' canonical links
  add(`/r/${lgSlug(r)}/${r.id}`, r);
  add(`/cat/${r.cat.toLowerCase()}`, r);
}
for (const pair of legacy.r_pairs) add(`/r/${pair}`, byId.get(pair.split('/').pop()));
for (const [from, to] of Object.entries(legacy.aliases)) add(`/cat/${from}`, byCat.get(to));

const dynamic = [
  '/section8recs/cat/:cat /cat/:cat 301', '/section8recs/releases /releases 301', '/section8recs / 301',
  '/player/cat/:cat /cat/:cat 301', '/player/:cat /cat/:cat 301',
  '/cat/:cat/* /cat/:cat 301',            // lgsites checkout pages (thanks, cancelled) and stray suffixes
  '/r/:slug/:id/* /releases 301',
  '/latest /releases 302', '/checkout /releases 301',
];
if (rules.size > 2000 || dynamic.length > 100) throw new Error(`too many redirects: ${rules.size} static, ${dynamic.length} dynamic`);
const text = '# generated by scripts/redirects.mjs\n' + [...rules].map(([f, t]) => `${f} ${t} 301`).join('\n') + '\n' + dynamic.join('\n') + '\n';
writeFileSync(ROOT + 'static/_redirects', text);
console.log(`redirects: ${rules.size} static, ${dynamic.length} dynamic`);
